import argparse
import os
import sys
from pathlib import Path

from infoparser.config import load_config
from infoparser.services import build


def _services(a):
    env = dict(os.environ)
    if a.home:
        env["INFOPARSER_HOME"] = a.home
    return build(load_config(Path(a.config) if a.config else None, env))


def _init(a):
    s = _services(a)
    for d in (s.cfg.blobs_dir, s.cfg.vault_dir, *s.cfg.watch_dirs[:1]):
        Path(d).mkdir(parents=True, exist_ok=True)
    print(f"initialized {s.cfg.home}")


def _submit(a):
    s = _services(a)
    if a.file:
        p = Path(a.file)
        r = s.inbox.submit(adapter="cli", file=p, filename=p.name, user_context=a.context)
    elif a.text:
        r = s.inbox.submit(adapter="cli", text=a.text, user_context=a.context)
    else:
        sys.exit("submit needs TEXT_OR_URL or --file")
    print(f"submitted {r.id}")


def _inbox(a):
    for r in _services(a).inbox.list(a.status):
        what = r["canonical_url"] or r["original_filename"] or (r["payload_text"] or "")[:50].replace("\n", " ")
        print(f"{r['id']}  {r['status']:<19} {r['content_type'] or '-':<8} {what}" + (f"  !{r['error']}" if r["error"] else ""))


def _retry(a):
    try:
        _services(a).inbox.retry(a.id)
    except KeyError:
        sys.exit(f"error: unknown id {a.id}")
    print(f"requeued {a.id}")


def _worker(a):
    from infoparser.pipeline import runner
    from infoparser.worker import Worker
    s = _services(a)
    w = Worker(s.conn, s.inbox, s.queue, lambda i: runner.process(s, i))
    if a.once:
        n = 0
        while w.run_once():
            n += 1
        print(f"processed {n} job(s)")
    else:
        try:
            w.run_forever()
        except KeyboardInterrupt:
            pass


def _cite_line(n, title, url, locator):
    return f"[{n}] {title} \u2014 {url or '-'} \u2014 {locator or '-'}"


def _search(a):
    from infoparser.retrieval.search import search_ex
    r = search_ex(_services(a), " ".join(a.query), limit=a.limit, mode=a.mode)
    for w in r.warnings:
        print(f"warning: {w}", file=sys.stderr)
    for n, h in enumerate(r.hits, 1):
        print(f"{_cite_line(n, h.title, h.source_url, h.locator)}\n    {h.item_id or 'segment'} [{h.kind}/{h.provenance}] {h.snippet}")


def _ask(a):
    import json
    from infoparser.retrieval.ask import ask
    ans = ask(_services(a), " ".join(a.question), limit=a.k)
    if a.json:
        print(json.dumps(ans.to_dict(), indent=2))
        return
    print(f"mode: {ans.mode} (retrieval: {ans.retrieval_mode})")
    if ans.interpretation:
        print(f"\n{ans.interpretation}\n(generated by {ans.generated_by}; interpretation, not source text)")
    if ans.message:
        print(ans.message)
    for e in ans.retrieved:
        print(_cite_line(e.n, e.title, e.deep_link or e.url, e.locator))
    for w in ans.warnings:
        print(f"warning: {w}", file=sys.stderr)
    if ans.egress:
        print(f"egress: text sent to remote backend(s): {', '.join(ans.egress)}", file=sys.stderr)


def _show(a):
    from infoparser.store.knowledge import get_item
    s = _services(a)
    try:
        r = s.inbox.get(a.id)
    except KeyError:
        k = get_item(s.conn, a.id)
        if not k:
            sys.exit(f"error: unknown id {a.id}")
        print(f"{k['id']} [{k['kind']}/{k['provenance']}] {k['title']}\n{k['body']}\nevidence: {k['data'].get('evidence')}")
        return
    print(f"{r['id']} status={r['status']} type={r['content_type']} attempts={r['attempts']}")
    if r["error"]:
        print(f"error: {r['error']}")
    if r["user_context"]:
        print(f"context: {r['user_context']}")
    for k in s.conn.execute("SELECT id FROM knowledge_items WHERE source_id=? AND deleted_at IS NULL", (r["source_id"],)):
        i = get_item(s.conn, k["id"])
        print(f"- {i['id']} [{i['kind']}/{i['provenance']}] {i['title']}: {i['body']}")
    for e in s.conn.execute("SELECT stage, status, detail FROM processing_events WHERE inbox_id=? ORDER BY id", (a.id,)):
        print(f"  event {e['stage']} {e['status']} {e['detail'] or ''}")


def _reindex(a):
    from infoparser.retrieval.index import reindex
    n = reindex(_services(a), prune_old=a.prune_old)
    print(f"reindexed {n} vectors" if n else "nothing to reindex (no embedding backend configured?)")


def _doctor(a):
    s = _services(a)
    print(f"home: {s.cfg.home}\ndb: {s.cfg.db_path}\nallow_remote: {s.cfg.allow_remote}")
    for d in s.registry.describe():
        print(f"backend: {d}")
    for k in s.registry.skipped:
        print(f"skipped: {k}")


ADAPTERS = ("fs", "telegram_export", "http")


def _adapters_list(a):
    for n in ADAPTERS:
        print(n)


def _watch(a):
    from infoparser.adapters.fs import FsAdapter
    s = _services(a)
    fa = FsAdapter(s.inbox, s.cfg.watch_dirs)
    if a.once:
        fa.poll()  # first sighting only records sizes; use two polls for a one-shot scan
        print(f"submitted {fa.poll()} file(s)")
        return
    try:
        fa.run_forever()
    except KeyboardInterrupt:
        pass


def _adapters_run(a):
    if a.name == "fs":
        return _watch(a)
    if a.name == "http":
        return _serve_http(a)
    sys.exit(f"error: adapter {a.name} is not a long-running adapter (use import-telegram)")


def _import_telegram(a):
    from infoparser.adapters.telegram_export import import_export
    r = import_export(_services(a).inbox, Path(a.path), since=a.since)
    print(f"submitted {r.submitted}, duplicates {r.duplicates}, skipped {r.skipped}")


def _serve_http(a):
    from infoparser.adapters.http_ingest import IngestServer
    s = _services(a)
    try:
        srv = IngestServer(s.cfg)
    except ValueError as e:
        sys.exit(f"error: {e}")
    print(f"listening on http://{srv.server_address[0]}:{srv.server_address[1]} (token in {s.cfg.home}/http_token)")
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        srv.server_close()


def main(argv=None):
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--home", default=argparse.SUPPRESS)
    common.add_argument("--config", default=argparse.SUPPRESS)
    p = argparse.ArgumentParser(prog="infoparser", parents=[common])
    p.set_defaults(home=None, config=None)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init", parents=[common]).set_defaults(f=_init)
    c = sub.add_parser("submit", parents=[common])
    c.add_argument("text", nargs="?")
    c.add_argument("--context")
    c.add_argument("--file")
    c.set_defaults(f=_submit)
    c = sub.add_parser("inbox", parents=[common])
    c.add_argument("--status")
    c.set_defaults(f=_inbox)
    c = sub.add_parser("retry", parents=[common])
    c.add_argument("id")
    c.set_defaults(f=_retry)
    c = sub.add_parser("worker", parents=[common])
    c.add_argument("--once", action="store_true")
    c.set_defaults(f=_worker)
    c = sub.add_parser("search", parents=[common])
    c.add_argument("query", nargs="+")
    c.add_argument("--limit", type=int, default=10)
    c.add_argument("--mode", choices=["fts", "hybrid"], default="hybrid")
    c.set_defaults(f=_search)
    c = sub.add_parser("ask", parents=[common])
    c.add_argument("question", nargs="+")
    c.add_argument("--json", action="store_true")
    c.add_argument("--k", type=int, default=8)
    c.set_defaults(f=_ask)
    c = sub.add_parser("show", parents=[common])
    c.add_argument("id")
    c.set_defaults(f=_show)
    c = sub.add_parser("reindex", parents=[common])
    c.add_argument("--prune-old", action="store_true")
    c.set_defaults(f=_reindex)
    sub.add_parser("doctor", parents=[common]).set_defaults(f=_doctor)
    c = sub.add_parser("adapters", parents=[common])
    asub = c.add_subparsers(dest="acmd", required=True)
    asub.add_parser("list", parents=[common]).set_defaults(f=_adapters_list)
    r = asub.add_parser("run", parents=[common])
    r.add_argument("name", choices=ADAPTERS)
    r.add_argument("--once", action="store_true")
    r.set_defaults(f=_adapters_run)
    c = sub.add_parser("watch", parents=[common])
    c.add_argument("--once", action="store_true")
    c.set_defaults(f=_watch)
    c = sub.add_parser("import-telegram", parents=[common])
    c.add_argument("path")
    c.add_argument("--since")
    c.set_defaults(f=_import_telegram)
    sub.add_parser("serve-http", parents=[common]).set_defaults(f=_serve_http)
    a = p.parse_args(argv)
    a.f(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
